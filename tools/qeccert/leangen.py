"""Leg C: generate a Lean 4 distance proof in the form of the Lean-QEC examples
and build it against a Lean-QEC checkout.

The generated file follows LeanQEC/Stabilizer/Examples/BB/BB72.lean (Ehatamm,
Lee, Wu, Tao, arXiv:2605.16523; Apache-2.0): check matrices and kernel bases
as flattened BitVec literals, rank bounds through `linear_indep_SAT_correct`,
orthogonality through `mutually_orth_nat_correct`, the two distance queries
`lt_dist_sat` discharged by `bv_decide`, and the final step
`bitvec_sat_translation_correct`.  Two differences from the shipped examples:
every matrix is introduced as `BitVecMatrix <literal>` (so no `decide` is
needed to relate a literal to a matrix expression), and dependent rows of the
check matrices are dropped beforehand (so the rank step needs no row
selection).  The theorem proved is

    theorem <Name>_dist : d ≤ <Name>_css.toBSM.distance (by norm_num)

where <Name>_css is built from the matrices printed in the generated file.
The axioms it depends on are printed by `#print axioms` and recorded.
"""
import hashlib
import os
import re
import shutil
import subprocess
import tempfile
import time

from . import certify, gf2

# The Lean-QEC commit the template was written against.
LEANQEC_COMMIT = "3ecc50283caaa257c9da3a000ab57c5401039e2e"

_IND_SIMP = """  simp only [linear_indep_SAT, nonzero, nonzero_aux, Nat.add_one_sub_one, Nat.lt_add_one,
      getElem!_pos, Nat.one_lt_ofNat, Nat.ofNat_pos, Bool.decide_or, Bool.decide_eq_true,
      Bool.or_eq_true, all_dot_zero, all_dot_zero_aux, dot_col_zero, dot_col_aux, Nat.reduceMul,
      BitVec.ofNat_eq_ofNat, Nat.reduceAdd, BitVec.reduceGetElem, Bool.and_true, one_mul,
      Nat.reduceLT, zero_mul, zero_add, Bool.and_false, Bool.false_bne, Bool.bne_false,
      bne_self_eq_false, add_zero, Bool.not_and, Bool.not_or, Bool.not_not, Bool.and_eq_true,
      Bool.not_eq_eq_eq_not, Bool.not_true, bne_iff_ne, ne_eq]"""

_DIST_SIMP = """  simp (maxSteps := 99999999) only [lt_dist_sat, Nat.reduceMul, loc_constraints, loc_constraints_aux, loc_constraints_ith,
  symmetry_constraints, symmetry_constraints_aux,  Nat.add_one_sub_one, Nat.lt_add_one, getElem!_pos, loc_constraints_ith_jth_aux,
  loc_constraints_ith_jth, one_mul, Nat.cast_ofNat, BitVec.ofNat_eq_ofNat, zero_mul, eq_iff_iff,
  Nat.reduceLT, Nat.one_lt_ofNat, Nat.cast_one, Nat.ofNat_pos, Nat.cast_zero, parity_constraints,
  parity_constraints_aux, BitVec.dot_product, dot_product_aux, BitVec.row,
  Bool.not_eq_eq_eq_not, Bool.not_true, bne_eq_false_iff_eq, decide_eq_true_eq, rowspace_constraints,
  rowspace_constraints_aux, not_and, and_imp]"""


def _flat(rows, n):
    """Flattened literal: bit i*n + j is entry (i, j)."""
    v = 0
    for i, r in enumerate(rows):
        v |= r << (i * n)
    return hex(v)


def _clog2(n):
    return (n - 1).bit_length()


def prepare(code):
    """Independent check rows and kernel bases, as used by the generated file."""
    n = code.n
    hx = [code.hx[i] for i in gf2.independent_rows(code.hx)]
    hz = [code.hz[i] for i in gf2.independent_rows(code.hz)]
    kx, kz = gf2.nullspace(hx, n), gf2.nullspace(hz, n)
    return hx, hz, kx, kz


def render(code, targets, name):
    """Lean source proving  d <= distance  with d = min(targets d_x, d_z)."""
    if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", name):
        raise ValueError("name must be a Lean identifier")
    n = code.n
    d = min(targets["d_x"], targets["d_z"])
    if not 1 <= d <= n:
        raise ValueError("target distance must be between 1 and n")
    hx, hz, kx, kz = prepare(code)
    rx, rz = len(hx), len(hz)
    nlog = _clog2(n)
    N = name
    out = [f"""/- Generated by qeccert (leangen.py) for code sha256 {code.sha256()}.
   Template after Lean-QEC, LeanQEC/Stabilizer/Examples/BB/BB72.lean (Apache-2.0),
   commit {LEANQEC_COMMIT[:12]}. Do not edit by hand. -/
import LeanQEC.ComputerAlgebra.BitVecSAT
import Lean.Elab.Tactic.BVDecide
import Std.Tactic.BVDecide
import LeanQEC.ComputerAlgebra.BitVecCorrectness
import LeanQEC.Stabilizer.BitVecSATToDist
set_option maxRecDepth 9999999
set_option exponentiation.threshold 1000000
set_option maxHeartbeats 0
set_option synthInstance.maxHeartbeats 0
"""]
    for tag, rows in (("X", hx), ("Z", hz), ("X_ker", kx), ("Z_ker", kz)):
        out.append(f"def {N}_{tag} : BitVec ({len(rows)} * {n}) := {_flat(rows, n)}\n"
                   f"def {N}_{tag}_mat := BitVecMatrix {N}_{tag}\n"
                   f"lemma {N}_{tag}_mat_correct : flatten_matrix {N}_{tag}_mat = {N}_{tag} := "
                   f"flatten_BitVecMatrix_id _\n")
    for tag, r in (("X", rx), ("Z", rz), ("X_ker", n - rx), ("Z_ker", n - rz)):
        out.append(f"""lemma {N}_{tag}_rank : {r} ≤ {N}_{tag}_mat.rank := by
  apply Matrix.rank_le_of_submatrix_independent _ id (strictMono_id)
  rw [Matrix.submatrix_id_id]
  rw [linear_indep_SAT_correct, {N}_{tag}_mat_correct, {N}_{tag}]
{_IND_SIMP}
  first | (bv_normalize; done) | bv_decide (timeout := 99999)
""")
    for lem, a, b in (("XZ_orth", "X", "Z"), ("X_ker_orth", "X", "X_ker"), ("Z_ker_orth", "Z", "Z_ker")):
        out.append(f"""lemma {N}_{lem} : {N}_{a}_mat.mutually_orth_rows {N}_{b}_mat := by
  rw [←mutually_orth_nat_correct, {N}_{a}_mat_correct, {N}_{b}_mat_correct]
  unfold bitvec_mutually_orth_nat
  native_decide
""")
    for lem, stab, ker in (("dist_z", "X", "Z_ker"), ("dist_x", "Z", "X_ker")):
        out.append(f"""lemma {N}_{lem} : lt_dist_sat {N}_{stab} {N}_{ker} {d - 1} {nlog} := by
  rw [{N}_{stab}, {N}_{ker}]
{_DIST_SIMP}
  bv_decide (timeout := 99999) (maxSteps := 99999999)
""")
    out.append(f"""lemma {N}_X_ker_is_ker : {N}_X_ker_mat.is_ker_for {N}_X_mat := by
  apply Matrix.is_ker_for_of_rank_sum_mutually_orth _ _ {N}_X_rank {N}_X_ker_rank (by norm_num) {N}_X_ker_orth
lemma {N}_Z_ker_is_ker : {N}_Z_ker_mat.is_ker_for {N}_Z_mat := by
  apply Matrix.is_ker_for_of_rank_sum_mutually_orth _ _ {N}_Z_rank {N}_Z_ker_rank (by norm_num) {N}_Z_ker_orth
def {N}_css : CSS_pair {n} {rx} {rz} :=
  CSS_pair.of_matrices {N}_X_mat {N}_Z_mat {N}_XZ_orth
theorem {N}_dist : {d} ≤ {N}_css.toBSM.distance (by norm_num) := by
  apply bitvec_sat_translation_correct {N}_css
      {N}_Z_ker_mat {N}_Z_ker_is_ker
      {N}_X_ker_mat {N}_X_ker_is_ker (by norm_num) _ _
  · rw [{N}_css, CSS_pair.of_matrices, {N}_X_mat_correct, {N}_Z_ker_mat_correct]
    exact {N}_dist_z
  rw [{N}_css, CSS_pair.of_matrices, {N}_Z_mat_correct, {N}_X_ker_mat_correct]
  exact {N}_dist_x
#print axioms {N}_dist
""")
    return "\n".join(out)


def find_lake():
    cand = os.environ.get("QECCERT_LAKE") or shutil.which("lake")
    if not cand:
        home = os.path.expanduser("~/.elan/bin/lake")
        cand = home if os.path.isfile(home) else None
    return cand


def unavailable():
    """None if the leg can run, else the reason (a named skip)."""
    root = os.environ.get("QECCERT_LEANQEC")
    if not root:
        return "QECCERT_LEANQEC is not set (path to a built Lean-QEC checkout)"
    if not os.path.isfile(os.path.join(root, "LeanQEC", "Stabilizer", "BitVecSATToDist.lean")):
        return f"{root} does not look like a Lean-QEC checkout"
    if not os.path.isdir(os.path.join(root, ".lake", "build")):
        return f"{root} has not been built (run `lake exe cache get && lake build` there)"
    if not find_lake():
        return "lake not found (PATH, QECCERT_LAKE or ~/.elan/bin/lake)"
    return None


def _checkout_commit(root):
    try:
        return subprocess.run(["git", "-C", root, "rev-parse", "HEAD"], capture_output=True,
                              text=True, timeout=10).stdout.strip() or None
    except (OSError, subprocess.TimeoutExpired):
        return None


STANDARD_AXIOMS = {"propext", "Classical.choice", "Quot.sound"}


def classify_axioms(axioms, name):
    """Split the axiom list into the three standard axioms, native-evaluation
    axioms introduced by the generated file (bv_decide, native_decide), and
    native-evaluation axioms inherited from Lean-QEC library lemmas."""
    ax = [a.rstrip("\u271d") for a in axioms]
    std = sorted(a for a in ax if a in STANDARD_AXIOMS)
    native = [a for a in ax if "._native." in a or a in ("Lean.ofReduceBool", "Lean.trustCompiler")]
    other = sorted(a for a in ax if a not in STANDARD_AXIOMS and a not in native)
    own = sorted(a for a in native if a.startswith(name + "_"))
    lib = sorted({a.split("._native.")[0] for a in native if not a.startswith(name + "_")})
    return dict(standard=std, native_generated=len(own), native_library_lemmas=lib, other=other)


def build_file(path, timeout):
    """Elaborate one generated file.  Returns (ok, axioms, seconds, tail)."""
    root = os.environ["QECCERT_LEANQEC"]
    lake = find_lake()
    env = dict(os.environ)
    env["PATH"] = os.path.dirname(lake) + os.pathsep + env.get("PATH", "")
    t0 = time.monotonic()
    try:
        p = subprocess.run([lake, "env", "lean", os.path.abspath(path)], cwd=root, env=env,
                           capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return False, None, timeout, f"lean exceeded {timeout} s"
    secs = round(time.monotonic() - t0, 1)
    text = p.stdout + p.stderr
    m = re.search(r"depends on axioms:\s*\[([^\]]*)\]", text, re.S)
    axioms = sorted(a.strip() for a in m.group(1).split(",")) if m else None
    errors = re.search(r"(^|\n)[^\n]*: error", text) is not None
    ok = (p.returncode == 0 and not errors and axioms is not None
          and "sorryAx" not in axioms)
    return ok, axioms, secs, text[-1500:]


def run_leg(receipt, code, targets=None, workdir=None, timeout=3600, name=None):
    """Prove d >= b in Lean, b = min of the targets (default: the witnessed
    upper bounds in the receipt).  On success the bound is attached to both
    d_x and d_z, since the theorem bounds the stabilizer-code distance."""
    targets = dict(targets or {})
    f = receipt["facts"]
    ev = dict(leg="C", quantity="d", method="Lean 4 kernel via Lean-QEC "
              "bitvec_sat_translation_correct, lt_dist_sat by bv_decide")
    for q in ("d_x", "d_z"):
        if q not in targets:
            targets[q] = f[q]["upper"]
    why = unavailable()
    if why is None and (targets["d_x"] is None or targets["d_z"] is None):
        why = "no target and no witnessed upper bound for d_x, d_z"
    if why:
        for q in ("d_x", "d_z"):
            receipt["evidence"].append(dict(ev, quantity=q, status="skipped", reason=why))
        return receipt
    b = min(targets["d_x"], targets["d_z"])
    name = name or "Qeccert_" + code.sha256()[:10]
    tmp = None
    if workdir is None:
        tmp = tempfile.mkdtemp(prefix="qeccert-lean-")
        workdir = tmp
    os.makedirs(workdir, exist_ok=True)
    path = os.path.join(workdir, f"{name}.lean")
    try:
        src = render(code, targets, name)
        with open(path, "w") as fh:
            fh.write(src)
        ok, axioms, secs, tail = build_file(path, timeout)
        hx, hz, _, _ = prepare(code)
        ev.update(theorem=f"{name}_dist : {b} ≤ {name}_css.toBSM.distance",
                  lean_sha256=hashlib.sha256(src.encode()).hexdigest(),
                  leanqec_commit=_checkout_commit(os.environ["QECCERT_LEANQEC"]),
                  template_commit=LEANQEC_COMMIT, axioms=axioms,
                  axiom_classes=classify_axioms(axioms, name) if axioms else None,
                  build_seconds=secs,
                  rows_used=[len(hx), len(hz)])
        if ok:
            for q in ("d_x", "d_z"):
                certify.add_lower_bound(receipt, q, b,
                                        dict(ev, quantity=q, status="proved", claim=f"{q} >= {b}"))
        elif tail.startswith("lean exceeded"):
            for q in ("d_x", "d_z"):
                receipt["evidence"].append(dict(ev, quantity=q, status="skipped", reason=tail))
        else:
            for q in ("d_x", "d_z"):
                receipt["evidence"].append(dict(ev, quantity=q, status="failed",
                                                reason="Lean did not accept the file: " + tail[-600:]))
    finally:
        if tmp:
            shutil.rmtree(tmp, ignore_errors=True)
    return receipt
