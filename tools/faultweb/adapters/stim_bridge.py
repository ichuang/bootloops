"""Pure-Stdlib `.stim` Circuit + `DETECTOR` Emitter and Optional `stim` Sampler Bridge.

Emits valid Stim circuit text (`R`, `RX`, `H`, `S`, `S_DAG`, `CX`, `CZ`, `SWAP`,
`M`, `MX`, `MY`, `TICK`, optional `DEPOLARIZE1`/`DEPOLARIZE2` or `X_ERROR`/`Z_ERROR`,
and exact `DETECTOR rec[-k]` annotations synthesized directly from `compile_outcome_map`
Pauli-web detecting regions!).

When the optional `stim` package is installed, `to_stim_circuit` and `sample_stim_detectors`
parse and execute the circuit in Stim's C++ engine without a single `float` literal in Python.

Zero float literals or float builtin references appear anywhere in this module.
"""

from __future__ import annotations

from decimal import Context, Decimal, ROUND_HALF_EVEN
from fractions import Fraction
from typing import Any

from ..contracts import parse_exact_rate, schedule_circuit_ticks
from ..diagram import CliffordCircuit, PREP_STATES, RefusalError, SINGLE_MEAS, circuit_to_zx_fe
from ..pauliweb import compile_outcome_map

_STIM_DEC_CTX = Context(prec=16, rounding=ROUND_HALF_EVEN)


def stim_available() -> bool:
    try:
        __import__("stim")
        return True
    except ImportError:
        return False


def _frac_to_stim_decimal_str(frac: Fraction) -> str:
    if frac == 0:
        return "0"
    val = _STIM_DEC_CTX.divide(Decimal(frac.numerator), Decimal(frac.denominator))
    return format(val.normalize(), "f")


def circuit_to_stim_text(
    circuit: CliffordCircuit,
    p_phys: str | Fraction = "0",
    idle_p_ratio: str | Fraction = "1",
    noise_model: str = "circuit_depolarizing",
    emit_detectors: bool = True,
) -> str:
    """Compile a physical `CliffordCircuit` into `.stim` text with Pauli-web `DETECTOR` lines."""
    p = parse_exact_rate(p_phys)
    idle_ratio = parse_exact_rate(idle_p_ratio) if str(idle_p_ratio).strip() != "1" else Fraction(1)
    p_idle = p * idle_ratio
    p_str = _frac_to_stim_decimal_str(p)
    p_idle_str = _frac_to_stim_decimal_str(p_idle)

    sched = schedule_circuit_ticks(circuit)
    lines: list[str] = [f"# Generated by faultweb ({circuit.name}, noise_model={noise_model})"]

    meas_order: list[str] = []
    for t_idx, tick_locs in enumerate(sched.tick_ops):
        for sloc in tick_locs:
            k = sloc.kind
            qs = sloc.qubits
            if sloc.is_idle:
                if p_idle > 0:
                    if noise_model == "circuit_depolarizing":
                        lines.append(f"DEPOLARIZE1({p_idle_str}) {qs[0]}")
                    else:
                        lines.append(f"X_ERROR({p_idle_str}) {qs[0]}")
                        lines.append(f"Z_ERROR({p_idle_str}) {qs[0]}")
                continue

            if k == "PREP_0":
                lines.append(f"R {qs[0]}")
            elif k == "PREP_1":
                lines.append(f"R {qs[0]}")
                lines.append(f"X {qs[0]}")
            elif k == "PREP_PLUS":
                lines.append(f"RX {qs[0]}")
            elif k == "PREP_MINUS":
                lines.append(f"RX {qs[0]}")
                lines.append(f"Z {qs[0]}")
            elif k == "I":
                lines.append(f"I {qs[0]}")
            elif k in ("H", "S", "X", "Y", "Z"):
                lines.append(f"{k} {qs[0]}")
            elif k == "SDG":
                lines.append(f"S_DAG {qs[0]}")
            elif k in ("CX", "CZ", "SWAP"):
                lines.append(f"{k} {qs[0]} {qs[1]}")
            elif k in SINGLE_MEAS:
                if p > 0:
                    if noise_model == "circuit_depolarizing":
                        lines.append(f"DEPOLARIZE1({p_str}) {qs[0]}")
                    else:
                        err_op = "X_ERROR" if k == "MEAS_Z" else "Z_ERROR"
                        lines.append(f"{err_op}({p_str}) {qs[0]}")
                m_inst = "M" if k == "MEAS_Z" else ("MX" if k == "MEAS_X" else "MY")
                lines.append(f"{m_inst} {qs[0]}")
                meas_order.append(sloc.label)

            if p > 0 and k not in SINGLE_MEAS:
                if len(qs) == 1:
                    if noise_model == "circuit_depolarizing":
                        lines.append(f"DEPOLARIZE1({p_str}) {qs[0]}")
                    else:
                        lines.append(f"X_ERROR({p_str}) {qs[0]}")
                        lines.append(f"Z_ERROR({p_str}) {qs[0]}")
                else:
                    if noise_model == "circuit_depolarizing":
                        lines.append(f"DEPOLARIZE2({p_str}) {qs[0]} {qs[1]}")
                    else:
                        lines.append(f"X_ERROR({p_str}) {qs[0]} {qs[1]}")
                        lines.append(f"Z_ERROR({p_str}) {qs[0]} {qs[1]}")

        if t_idx + 1 < len(sched.tick_ops):
            lines.append("TICK")

    if emit_detectors and meas_order:
        omap = compile_outcome_map(circuit_to_zx_fe(circuit, "fault_free"))
        lbl_to_rec_pos = {lbl: idx for idx, lbl in enumerate(meas_order)}
        total_m = len(meas_order)
        for chk_mask in omap.parity_checks:
            recs: list[str] = []
            for b_i, lbl in enumerate(omap.meas_labels):
                if (chk_mask >> b_i) & 1:
                    r_pos = lbl_to_rec_pos[lbl]
                    offset = r_pos - total_m  # negative Stim `rec[-offset]` index!
                    recs.append(f"rec[{offset}]")
            if recs:
                lines.append("DETECTOR " + " ".join(recs))

    return "\n".join(lines) + "\n"


def to_stim_circuit(
    circuit: CliffordCircuit,
    p_phys: str | Fraction = "0",
    idle_p_ratio: str | Fraction = "1",
    noise_model: str = "circuit_depolarizing",
    emit_detectors: bool = True,
) -> Any:
    """Build a live `stim.Circuit` object when `stim` is installed."""
    if not stim_available():
        raise RefusalError("STIM-NOT-INSTALLED", "optional dependency `stim` is not installed in this Python")
    import stim  # type: ignore

    txt = circuit_to_stim_text(
        circuit,
        p_phys=p_phys,
        idle_p_ratio=idle_p_ratio,
        noise_model=noise_model,
        emit_detectors=emit_detectors,
    )
    return stim.Circuit(txt)


def sample_stim_detectors(
    circuit: CliffordCircuit,
    shots: int = 1024,
    p_phys: str | Fraction = "0",
    noise_model: str = "circuit_depolarizing",
    seed: int = 0,
) -> dict[str, int]:
    """Sample synthesized `DETECTOR` events in Stim and return exact integer hit counts."""
    sc = to_stim_circuit(circuit, p_phys=p_phys, noise_model=noise_model, emit_detectors=True)
    sampler = sc.compile_detector_sampler(seed=seed)
    batch = sampler.sample(shots=shots)
    any_det_shots = sum(1 for row in batch if any(bool(x) for x in row))
    return {
        "shots": shots,
        "num_detectors": int(sc.num_detectors),
        "triggered_shots": any_det_shots,
        "quiet_shots": shots - any_det_shots,
    }
