"""Semantic w-Fault Equivalence, Circuit Distance, and Codespace Preconditioning.

Implements Definitions 2.8, 3.1, Proposition 3.7, Theorem 3.11, and Proposition C.1
of Rodatz, Poor, and Kissinger (arXiv:2506.17181v4), with exact grouped-location
weight accounting (Definition 2.3) and optional dual-lineage (`pauliweb` vs `spackle`)
cross-verification.

Note on CSS circuit-level noise (`noise_model == "circuit_css"`, Kissinger §7.2.2 p. 38):
  Circuit-level CSS noise analyzes the X-sector atomic fault model and the Z-sector
  atomic fault model *separately* (rather than generating cross-sector Y = XZ combinations
  between X and Z atomic events). Every verdict and receipt records `noise_model` explicitly
  so a `circuit_css` equivalence is never misreported as `circuit_depolarizing`.

Zero float literals appear anywhere in this module.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any

from .diagram import (
    AtomicFaultGroup,
    CircuitOp,
    CliffordCircuit,
    RefusalError,
    VALID_NOISE_MODELS,
    ZXDiagram,
    circuit_to_zx_fe,
)
from .frame_oracle import analyze_circuit_spackle
from .pauliweb import FaultSignatureTables, analyze_pauli_webs, build_fault_signature_tables


@dataclass(frozen=True)
class CSSCodeSpec:
    """Self-contained CSS stabiliser code specification [[n, k, d]]."""

    name: str
    n: int
    k: int
    d: int
    hx_rows: tuple[int, ...]      # X-stabiliser supports as n-bit ints (bit q = wire q)
    hz_rows: tuple[int, ...]      # Z-stabiliser supports as n-bit ints
    lx_rows: tuple[int, ...]      # k logical X supports as n-bit ints
    lz_rows: tuple[int, ...]      # k logical Z supports as n-bit ints

    def stabilizers_pauli_strings(self) -> list[str]:
        out: list[str] = []
        for row in self.hx_rows:
            out.append("".join("X" if (row >> q) & 1 else "I" for q in range(self.n)))
        for row in self.hz_rows:
            out.append("".join("Z" if (row >> q) & 1 else "I" for q in range(self.n)))
        return out

    def logical_x_strings(self) -> list[str]:
        return [
            "".join("X" if (row >> q) & 1 else "I" for q in range(self.n))
            for row in self.lx_rows
        ]

    def logical_z_strings(self) -> list[str]:
        return [
            "".join("Z" if (row >> q) & 1 else "I" for q in range(self.n))
            for row in self.lz_rows
        ]

    def to_dict(self) -> dict[str, Any]:
        return {
            "name": self.name,
            "n": self.n,
            "k": self.k,
            "d": self.d,
            "hx_rows": list(self.hx_rows),
            "hz_rows": list(self.hz_rows),
            "lx_rows": list(self.lx_rows),
            "lz_rows": list(self.lz_rows),
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> CSSCodeSpec:
        return cls(
            name=str(data["name"]),
            n=int(data["n"]),
            k=int(data["k"]),
            d=int(data["d"]),
            hx_rows=tuple(int(x) for x in data["hx_rows"]),
            hz_rows=tuple(int(x) for x in data["hz_rows"]),
            lx_rows=tuple(int(x) for x in data["lx_rows"]),
            lz_rows=tuple(int(x) for x in data["lz_rows"]),
        )


def make_steane_7_1_3() -> CSSCodeSpec:
    """Steane [[7, 1, 3]] code in Kissinger Appendix C.2 column order:
      r0 = 1111000 (wires 0,1,2,3) -> 0b0001111 = 15
      r1 = 0110110 (wires 1,2,4,5) -> 0b0110110 = 54
      r2 = 0011011 (wires 2,3,5,6) -> 0b1101100 = 108
      L  = 1111111 (wires 0..6)    -> 0b1111111 = 127.
    """
    rows = (15, 54, 108)
    return CSSCodeSpec(
        name="steane_7_1_3",
        n=7,
        k=1,
        d=3,
        hx_rows=rows,
        hz_rows=rows,
        lx_rows=(127,),
        lz_rows=(127,),
    )


def make_shor_9_1_3() -> CSSCodeSpec:
    """Shor [[9, 1, 3]] code."""
    hz = (
        0b000000011,
        0b000000110,
        0b000011000,
        0b000110000,
        0b011000000,
        0b110000000,
    )
    hx = (
        0b000111111,
        0b111111000,
    )
    return CSSCodeSpec(
        name="shor_9_1_3",
        n=9,
        k=1,
        d=3,
        hx_rows=hx,
        hz_rows=hz,
        lx_rows=(0b111111111,),
        lz_rows=(0b111111111,),
    )


def make_golay_23_1_7() -> CSSCodeSpec:
    """Self-dual binary Golay [[23, 1, 7]] code generated by cyclic polynomial 0xAE3 (1 + x + x^5 + x^6 + x^7 + x^9 + x^11)."""
    # Dual generator of [23, 12, 7] cyclic Golay code: check polynomial of degree 12 -> 11 rows of weight 8!
    # Wait: g(x) = x^11 + x^9 + x^7 + x^6 + x^5 + x + 1 has weight 7; (1+x)*g(x) has weight 8 and generates C_perp [23, 11, 8]!
    g_dual = 0b101011100011 ^ (0b101011100011 << 1)  # degree 12, weight 8!
    rows = tuple(g_dual << shift for shift in range(11))
    all23 = (1 << 23) - 1
    return CSSCodeSpec(
        name="golay_23_1_7",
        n=23,
        k=1,
        d=7,
        hx_rows=rows,
        hz_rows=rows,
        lx_rows=(all23,),
        lz_rows=(all23,),
    )


BUILTIN_CODES: dict[str, Any] = {
    "steane_7_1_3": make_steane_7_1_3,
    "shor_9_1_3": make_shor_9_1_3,
    "golay_23_1_7": make_golay_23_1_7,
}


def resolve_code(name_or_dict: str | dict[str, Any] | CSSCodeSpec) -> CSSCodeSpec:
    if isinstance(name_or_dict, CSSCodeSpec):
        return name_or_dict
    if isinstance(name_or_dict, str):
        if name_or_dict in BUILTIN_CODES:
            return BUILTIN_CODES[name_or_dict]()
        raise RefusalError("UNKNOWN-CODE-PRESET", f"unknown built-in code {name_or_dict!r}")
    return CSSCodeSpec.from_dict(name_or_dict)


def prepend_ideal_encoder(circuit: CliffordCircuit, code: CSSCodeSpec) -> CliffordCircuit:
    """Prepend an idealised fault-free encoder `enc` to `circuit` (Kissinger Proposition C.1).

    The logical inputs to `enc` are marked fault-free (`fault_free_wires`), while the `n`
    physical data wires leaving `enc` and entering `circuit` retain normal physical noise
    (unless `circuit` itself marked them fault-free), matching Proposition C.1 on p. 57.
    """
    circuit.validate()
    if len(circuit.input_qubits) != code.n:
        raise RefusalError(
            "CODESPACE-INPUT-MISMATCH",
            f"circuit has {len(circuit.input_qubits)} inputs, code {code.name} has n={code.n}",
        )
    base_q = circuit.n_qubits
    log_inputs = tuple(base_q + r for r in range(code.k))
    enc_op = CircuitOp(
        kind="ENC_PREP",
        qubits=circuit.input_qubits,
        mode="ff",
        label=f"ideal_enc_{code.name}",
        params={
            "input_qubits": list(log_inputs),
            "stabilizers": code.stabilizers_pauli_strings(),
            "logical_x": code.logical_x_strings(),
            "logical_z": code.logical_z_strings(),
        },
    )
    ff_wires = set(circuit.fault_free_wires)
    for lq in log_inputs:
        ff_wires.add((lq, 0))
    return CliffordCircuit(
        n_qubits=circuit.n_qubits + code.k,
        input_qubits=log_inputs,
        output_qubits=circuit.output_qubits,
        ops=[enc_op] + list(circuit.ops),
        fault_free_wires=frozenset(ff_wires),
        all_wires_fault_free=circuit.all_wires_fault_free,
        name=f"{code.name}_enc__{circuit.name}",
    )


def _compute_undetectable_min_weights(
    fault_groups: tuple[AtomicFaultGroup, ...],
    group_col_ranges: tuple[tuple[int, int], ...],
    det_rows: tuple[int, ...],
    eff_rows: tuple[int, ...],
    max_weight: int,
    sector_filter: str | None = None,
    state_cap: int = 500_000,
) -> tuple[dict[int, tuple[int, tuple[str, ...]]], bool]:
    """Exact BFS over deduplicated single-group `(det_syn, eff_syn)` subspace pairs.

    Because each `AtomicFaultGroup` is closed under XOR (a linear subspace), the minimum
    group-weight needed to achieve any `(det_syn, eff_syn)` equals the minimum word length
    in the deduplicated weight-1 generator set `Sigma_1`!

    Returns:
      (undetectable_map, hit_state_cap)
      where `undetectable_map[eff_syn] = (min_weight, (group_labels...))` for all
      undetectable effects (`det_syn == 0`) reachable in <= `max_weight` atomic events.
    """
    if max_weight <= 0:
        return ({0: (0, ())}, False)

    def eval_pair(gbits: int) -> tuple[int, int]:
        ds = 0
        for i, r in enumerate(det_rows):
            if (r & gbits).bit_count() & 1:
                ds |= 1 << i
        es = 0
        for i, r in enumerate(eff_rows):
            if (r & gbits).bit_count() & 1:
                es |= 1 << i
        return ds, es

    sigma1: dict[tuple[int, int], str] = {}
    for grp, (lo, hi) in zip(fault_groups, group_col_ranges):
        if sector_filter is not None and grp.sector != sector_filter:
            continue
        width = hi - lo
        for sub in range(1, 1 << width):
            pair = eval_pair(sub << lo)
            if pair != (0, 0) and pair not in sigma1:
                sigma1[pair] = f"{grp.label}[0x{sub:x}]"

    s1_items = list(sigma1.items())
    visited: dict[tuple[int, int], tuple[int, tuple[str, ...]]] = {(0, 0): (0, ())}
    frontier: list[tuple[tuple[int, int], tuple[str, ...]]] = [((0, 0), ())]

    for step_w in range(1, max_weight + 1):
        next_frontier: list[tuple[tuple[int, int], tuple[str, ...]]] = []
        for (dp, ep), w_prev in frontier:
            for (d1, e1), lbl1 in s1_items:
                nxt = (dp ^ d1, ep ^ e1)
                if nxt not in visited:
                    w_nxt = w_prev + (lbl1,)
                    visited[nxt] = (step_w, w_nxt)
                    next_frontier.append((nxt, w_nxt))
                    if len(visited) > state_cap:
                        raise RefusalError(
                            "FAULT-ENUM-BUDGET-EXCEEDED",
                            f"reachable syndrome state space exceeded cap={state_cap} at weight {step_w}; "
                            f"use constructive ZX rewrite verification (`verify_derivation`) at large scale",
                        )
        frontier = next_frontier
        if not frontier:
            break

    undet: dict[int, tuple[int, tuple[str, ...]]] = {}
    for (ds, es), val in visited.items():
        if ds == 0:
            undet[es] = val
    return undet, False


@dataclass(frozen=True)
class DistanceResult:
    """Result of `circuit_distance` (Definition 2.8 & Proposition 3.7)."""

    noise_model: str
    w_max_checked: int
    exact_distance: int | None          # None means dist > w_max_checked (certified lower bound w_max_checked + 1)
    lower_bound: int
    witness_fault: tuple[str, ...]
    witness_effect: int

    def to_dict(self) -> dict[str, Any]:
        return {
            "noise_model": self.noise_model,
            "w_max_checked": self.w_max_checked,
            "exact_distance": self.exact_distance,
            "lower_bound": self.lower_bound,
            "witness_fault": list(self.witness_fault),
            "witness_effect": self.witness_effect,
        }


def circuit_distance(
    target: CliffordCircuit | ZXDiagram,
    w_max: int = 4,
    noise_model: str = "circuit_depolarizing",
    codespace: CSSCodeSpec | None = None,
    cross_check_spackle: bool = True,
) -> DistanceResult:
    """Compute exact circuit distance dist_F(target) up to `w_max` (Definition 2.8)."""
    if w_max < 1:
        raise RefusalError("INVALID-WEIGHT-BOUND", f"w_max must be >= 1, got {w_max}")
    obj = prepend_ideal_encoder(target, codespace) if (codespace and isinstance(target, CliffordCircuit)) else target
    zx = circuit_to_zx_fe(obj, noise_model=noise_model) if isinstance(obj, CliffordCircuit) else obj
    ft = build_fault_signature_tables(zx, noise_model=noise_model)

    sectors = ("X", "Z") if noise_model == "circuit_css" else (None,)
    best_d: int | None = None
    best_wit: tuple[str, ...] = ()
    best_eff = 0

    for sec in sectors:
        undet, _ = _compute_undetectable_min_weights(
            ft.fault_groups,
            ft.group_col_ranges,
            ft.det_rows,
            ft.eff_rows,
            max_weight=w_max,
            sector_filter=sec,
        )
        for eff, (wt, wit) in undet.items():
            if eff != 0 and (best_d is None or wt < best_d):
                best_d = wt
                best_wit = wit
                best_eff = eff

    if cross_check_spackle and isinstance(obj, CliffordCircuit):
        sp = analyze_circuit_spackle(obj, noise_model=noise_model)
        best_sp: int | None = None
        for sec in sectors:
            undet_sp, _ = _compute_undetectable_min_weights(
                sp.fault_groups,
                sp.group_col_ranges,
                sp.det_rows,
                sp.eff_rows,
                max_weight=w_max,
                sector_filter=sec,
            )
            for eff, (wt, _) in undet_sp.items():
                if eff != 0 and (best_sp is None or wt < best_sp):
                    best_sp = wt
        if best_sp != best_d:
            raise AssertionError(
                f"Disjoint-lineage distance disagreement on {obj.name}: pauliweb={best_d} vs spackle={best_sp}"
            )

    return DistanceResult(
        noise_model=noise_model,
        w_max_checked=w_max,
        exact_distance=best_d,
        lower_bound=best_d if best_d is not None else (w_max + 1),
        witness_fault=best_wit,
        witness_effect=best_eff,
    )


@dataclass(frozen=True)
class FaultEquivResult:
    """Bidirectional w-fault-equivalence verdict (Definition 3.1)."""

    verdict: str                  # 'FAULT-EQUIV-PASS' | 'FAULT-EQUIV-FAIL' | 'MAP-MISMATCH'
    equivalent: bool
    w: int
    noise_model_lhs: str
    noise_model_rhs: str
    codespace_name: str | None
    spackle_crosschecked: bool
    checked_classes_lhs: int
    checked_classes_rhs: int
    counterexample: dict[str, Any] | None = None

    def to_dict(self) -> dict[str, Any]:
        return {
            "verdict": self.verdict,
            "equivalent": self.equivalent,
            "w": self.w,
            "noise_model_lhs": self.noise_model_lhs,
            "noise_model_rhs": self.noise_model_rhs,
            "codespace": self.codespace_name,
            "spackle_crosschecked": self.spackle_crosschecked,
            "checked_classes_lhs": self.checked_classes_lhs,
            "checked_classes_rhs": self.checked_classes_rhs,
            "counterexample": self.counterexample,
        }


def check_fault_equiv(
    lhs: CliffordCircuit | ZXDiagram,
    rhs: CliffordCircuit | ZXDiagram,
    w: int,
    noise_model_lhs: str = "circuit_depolarizing",
    noise_model_rhs: str | None = None,
    codespace: CSSCodeSpec | None = None,
    cross_check_spackle: bool = True,
) -> FaultEquivResult:
    """Verify whether `lhs` under `noise_model_lhs` is w-fault-equivalent to `rhs` (Def. 3.1).

    Checks all undetectable faults of location-weight k < w in both directions (`lhs -> rhs`
    and `rhs -> lhs`), and cross-verifies against the disjoint `frame_oracle` whenever both
    inputs are `CliffordCircuit` instances.
    """
    if w < 1:
        raise RefusalError("INVALID-WEIGHT-BOUND", f"w must be >= 1, got {w}")
    nm_rhs = noise_model_rhs if noise_model_rhs is not None else noise_model_lhs
    if noise_model_lhs not in VALID_NOISE_MODELS or nm_rhs not in VALID_NOISE_MODELS:
        raise RefusalError("UNKNOWN-NOISE-MODEL", f"invalid noise models ({noise_model_lhs!r}, {nm_rhs!r})")

    obj_l = prepend_ideal_encoder(lhs, codespace) if (codespace and isinstance(lhs, CliffordCircuit)) else lhs
    obj_r = prepend_ideal_encoder(rhs, codespace) if (codespace and isinstance(rhs, CliffordCircuit)) else rhs

    zx_l = circuit_to_zx_fe(obj_l, noise_model=noise_model_lhs) if isinstance(obj_l, CliffordCircuit) else obj_l
    zx_r = circuit_to_zx_fe(obj_r, noise_model=nm_rhs) if isinstance(obj_r, CliffordCircuit) else obj_r

    ana_l = analyze_pauli_webs(zx_l)
    ana_r = analyze_pauli_webs(zx_r)
    if (not ana_l.is_nonzero) or (not ana_r.is_nonzero):
        if ana_l.is_nonzero != ana_r.is_nonzero:
            return FaultEquivResult(
                verdict="MAP-MISMATCH",
                equivalent=False,
                w=w,
                noise_model_lhs=noise_model_lhs,
                noise_model_rhs=nm_rhs,
                codespace_name=codespace.name if codespace else None,
                spackle_crosschecked=False,
                checked_classes_lhs=0,
                checked_classes_rhs=0,
                counterexample={"reason": "one diagram is identically zero and the other is non-zero"},
            )
        return FaultEquivResult(
            verdict="FAULT-EQUIV-PASS",
            equivalent=True,
            w=w,
            noise_model_lhs=noise_model_lhs,
            noise_model_rhs=nm_rhs,
            codespace_name=codespace.name if codespace else None,
            spackle_crosschecked=False,
            checked_classes_lhs=0,
            checked_classes_rhs=0,
        )

    if ana_l.signed_boundary_stabs != ana_r.signed_boundary_stabs:
        return FaultEquivResult(
            verdict="MAP-MISMATCH",
            equivalent=False,
            w=w,
            noise_model_lhs=noise_model_lhs,
            noise_model_rhs=nm_rhs,
            codespace_name=codespace.name if codespace else None,
            spackle_crosschecked=False,
            checked_classes_lhs=0,
            checked_classes_rhs=0,
            counterexample={"reason": "fault-free signed boundary stabiliser tableaux differ"},
        )

    ft_l = build_fault_signature_tables(zx_l, noise_model=noise_model_lhs, analysis=ana_l)
    ft_r = build_fault_signature_tables(zx_r, noise_model=nm_rhs, analysis=ana_r)

    css_mode = (noise_model_lhs == "circuit_css") or (nm_rhs == "circuit_css")
    sectors = ("X", "Z") if css_mode else (None,)

    max_k = w - 1
    total_l = 0
    total_r = 0
    cex: dict[str, Any] | None = None

    for sec in sectors:
        ul, _ = _compute_undetectable_min_weights(
            ft_l.fault_groups, ft_l.group_col_ranges, ft_l.det_rows, ft_l.eff_rows, max_k, sector_filter=sec
        )
        ur, _ = _compute_undetectable_min_weights(
            ft_r.fault_groups, ft_r.group_col_ranges, ft_r.det_rows, ft_r.eff_rows, max_k, sector_filter=sec
        )
        total_l += len(ul)
        total_r += len(ur)

        # Check LHS -> RHS (smallest offending weight first)
        for eff, (wt_l, wit_l) in sorted(ul.items(), key=lambda kv: (kv[1][0], kv[0])):
            wt_r_entry = ur.get(eff)
            if wt_r_entry is None or wt_r_entry[0] > wt_l:
                cex = {
                    "direction": "lhs_to_rhs",
                    "sector": sec or "ALL",
                    "fault_weight": wt_l,
                    "fault_witness": list(wit_l),
                    "boundary_syndrome": eff,
                    "other_side_min_weight_within_bound": wt_r_entry[0] if wt_r_entry else None,
                }
                break
        if cex is not None:
            break

        # Check RHS -> LHS
        for eff, (wt_r, wit_r) in sorted(ur.items(), key=lambda kv: (kv[1][0], kv[0])):
            wt_l_entry = ul.get(eff)
            if wt_l_entry is None or wt_l_entry[0] > wt_r:
                cex = {
                    "direction": "rhs_to_lhs",
                    "sector": sec or "ALL",
                    "fault_weight": wt_r,
                    "fault_witness": list(wit_r),
                    "boundary_syndrome": eff,
                    "other_side_min_weight_within_bound": wt_l_entry[0] if wt_l_entry else None,
                }
                break
        if cex is not None:
            break

    pw_pass = cex is None
    did_spackle = False

    if cross_check_spackle and isinstance(obj_l, CliffordCircuit) and isinstance(obj_r, CliffordCircuit):
        sp_l = analyze_circuit_spackle(obj_l, noise_model=noise_model_lhs)
        sp_r = analyze_circuit_spackle(obj_r, noise_model=nm_rhs)
        if sp_l.signed_boundary_stabs != sp_r.signed_boundary_stabs:
            raise AssertionError("Disjoint-lineage map mismatch between pauliweb and spackle")
        sp_pass = True
        for sec in sectors:
            sul, _ = _compute_undetectable_min_weights(
                sp_l.fault_groups, sp_l.group_col_ranges, sp_l.det_rows, sp_l.eff_rows, max_k, sector_filter=sec
            )
            sur, _ = _compute_undetectable_min_weights(
                sp_r.fault_groups, sp_r.group_col_ranges, sp_r.det_rows, sp_r.eff_rows, max_k, sector_filter=sec
            )
            for eff, (wt_l, _) in sul.items():
                if eff not in sur or sur[eff][0] > wt_l:
                    sp_pass = False
                    break
            if not sp_pass:
                break
            for eff, (wt_r, _) in sur.items():
                if eff not in sul or sul[eff][0] > wt_r:
                    sp_pass = False
                    break
            if not sp_pass:
                break
        if sp_pass != pw_pass:
            raise AssertionError(
                f"Disjoint-lineage w={w} fault-equivalence disagreement: pauliweb={pw_pass} vs spackle={sp_pass}"
            )
        did_spackle = True

    return FaultEquivResult(
        verdict="FAULT-EQUIV-PASS" if pw_pass else "FAULT-EQUIV-FAIL",
        equivalent=pw_pass,
        w=w,
        noise_model_lhs=noise_model_lhs,
        noise_model_rhs=nm_rhs,
        codespace_name=codespace.name if codespace else None,
        spackle_crosschecked=did_spackle,
        checked_classes_lhs=total_l,
        checked_classes_rhs=total_r,
        counterexample=cex,
    )
